#!/usr/bin/env python3
"""Make the compact HakiOS Star2 S6E3HA8 tables from a Samsung/Apollo tree."""
import pathlib
import re
import sys

if len(sys.argv) != 3:
    raise SystemExit("usage: extract-star2-panel.py APOLLO OUT.h")
root = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])
base = root / "drivers/video/fbdev/exynos/panel/s6e3ha8"
dim = (base / "s6e3ha8_star2_a3_s0_panel_dimming.h").read_text()
panel = (base / "s6e3ha8_star2_a3_s0_panel.h").read_text()

def numbers(name, text):
    match = re.search(r"(?:s32|unsigned int)\s+" + re.escape(name) + r"\s*\[[^;=]*\]\s*=\s*\{(.*?)\};", text, re.S)
    if not match:
        raise SystemExit("missing " + name)
    return [int(x, 0) for x in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", match.group(1))]

luts = re.findall(r"DIM_LUT_V0_INIT\((\d+),\s*(\d+),\s*(GAMMA_2_(?:15|20)),\s*(star2_a3_s0_rtbl\w+),\s*(star2_a3_s0_ctbl\w+)\)", dim)
if len(luts) != 74:
    raise SystemExit(f"expected 74 dimming rows, found {len(luts)}")

# PAC 3.0 uses the 512-entry AOR table. Map each UI level to the first PAC
# brightness step at or above level*100, matching panel_bl.c.
steps = numbers("star2_a3_s0_brt_to_step_tbl", dim)
section = panel[panel.index("#if PANEL_BACKLIGHT_PAC_STEPS == 512"):panel.index("#elif PANEL_BACKLIGHT_PAC_STEPS == 256")]
pairs = re.search(r"star2_a3_s0_aor_table[^=]*=\s*\{(.*?)\};", section, re.S)
if not pairs:
    raise SystemExit("missing Star2 512-step AOR table")
aor_bytes = [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+", pairs.group(1))]
aor512 = [(aor_bytes[i] << 8) | aor_bytes[i + 1] for i in range(0, len(aor_bytes), 2)]
aor = []
for level in range(256):
    wanted = level * 100
    index = next((i for i, value in enumerate(steps) if value >= wanted), len(aor512) - 1)
    if index >= len(aor512):
        raise SystemExit(f"UI level {level} selects missing AOR index {index}")
    aor.append(aor512[index])

lines = [
    "/* Generated by tools/extract-star2-panel.py from Apollo/Samsung's GPL-2.0 Star2 panel tables. */",
    "#ifndef _HAKIOS_S6E3HA8_STAR2_H_",
    "#define _HAKIOS_S6E3HA8_STAR2_H_",
    "static const struct ha8_row ha8_rows_star2[HA8_ROWS] = {",
]
for nits, base_nits, gamma, rname, cname in luts:
    gray, color = numbers(rname, dim), numbers(cname, dim)
    if len(gray) != 11 or len(color) != 33:
        raise SystemExit(f"bad row {nits}: {len(gray)} gray, {len(color)} colour")
    colors = ", ".join("{ %d, %d, %d }" % tuple(color[i:i + 3]) for i in range(0, 33, 3))
    lines += [
        "\t{ %s, %s, %s, { %s }," % (nits, base_nits, "HA8_G220" if gamma.endswith("20") else "HA8_G215", ", ".join(map(str, gray))),
        "\t  { %s } }," % colors,
    ]
lines += ["};", "", "static const uint16_t ha8_aor_star2[256] = {"]
for i in range(0, 256, 12):
    lines.append("\t" + ", ".join("0x%04X" % value for value in aor[i:i + 12]) + ",")
lines += ["};", "#endif"]
out.write_text("\n".join(lines) + "\n")
